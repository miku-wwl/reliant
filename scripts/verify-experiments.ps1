<#
.SYNOPSIS
    Verify the Phase 2 and Phase 3 owner-experiment inventory.
.DESCRIPTION
    Discovers the test assembly once, then requires every Exp1..Exp12 and
    Exp1..Exp15 namespace to contain at least one executable test and exactly
    one matching learning report. With -Run, executes all selected experiments
    and writes a TRX file.
.PARAMETER Phase
    All, 2, or 3.
.PARAMETER Run
    Execute the selected experiment tests after validating discovery/evidence.
.PARAMETER SkipBuild
    Reuse an existing Debug build (used by CI after scripts/verify.ps1).
#>
param(
    [ValidateSet("All", "2", "3")]
    [string]$Phase = "All",
    [switch]$Run,
    [switch]$SkipBuild,
    [string]$ArtifactDir = ""
)

$ErrorActionPreference = "Stop"
$root = Resolve-Path "$PSScriptRoot/.."
$testProject = Join-Path $root "tests/Reliant.Tests/Reliant.Tests.csproj"
if (-not $ArtifactDir) {
    $ArtifactDir = Join-Path $root "artifacts"
}
New-Item -ItemType Directory -Force -Path $ArtifactDir | Out-Null

if (-not $SkipBuild) {
    dotnet build $testProject --configuration Debug
    if ($LASTEXITCODE -ne 0) { exit 1 }
}

$definitions = @()
if ($Phase -in @("All", "2")) {
    1..12 | ForEach-Object {
        $definitions += [pscustomobject]@{
            Phase = 2
            Experiment = $_
            Namespace = "Reliant.Tests.Integration.Phase2.Exp$_."
            ReportPattern = "learning/phase-2/exp$($_)-*.md"
        }
    }
}
if ($Phase -in @("All", "3")) {
    1..15 | ForEach-Object {
        $definitions += [pscustomobject]@{
            Phase = 3
            Experiment = $_
            Namespace = "Reliant.Tests.Integration.Phase3.Exp$_."
            ReportPattern = "learning/phase-3/exp$($_)-*.md"
        }
    }
}

$discoveryOutput = dotnet test $testProject --no-build --configuration Debug --list-tests 2>&1
if ($LASTEXITCODE -ne 0) {
    $discoveryOutput | Write-Host
    exit 1
}
$testNames = @(
    $discoveryOutput |
        Where-Object { $_ -match '^\s+Reliant\.Tests\.' } |
        ForEach-Object { $_.Trim() }
)

$rows = @()
$failed = $false
foreach ($definition in $definitions) {
    $testCount = @(
        $testNames |
            Where-Object {
                $_.StartsWith(
                    $definition.Namespace,
                    [StringComparison]::Ordinal)
            }
    ).Count
    $reports = @(
        Get-ChildItem -Path (Join-Path $root $definition.ReportPattern) -File -ErrorAction SilentlyContinue
    )
    $reportCount = $reports.Count
    $status = if ($testCount -gt 0 -and $reportCount -eq 1) {
        "PASS"
    } else {
        $failed = $true
        "FAIL"
    }
    $rows += [pscustomobject]@{
        Phase = $definition.Phase
        Experiment = $definition.Experiment
        Tests = $testCount
        Reports = $reportCount
        Status = $status
    }
    Write-Host (
        "[experiment gate] Phase {0} Exp{1}: tests={2}, reports={3}, {4}" -f
        $definition.Phase,
        $definition.Experiment,
        $testCount,
        $reportCount,
        $status)
}

$summaryPath = Join-Path $ArtifactDir "experiment-summary.md"
$summaryLines = @(
    "# Owner Experiment Discovery Summary",
    "",
    "Generated by scripts/verify-experiments.ps1.",
    "",
    "| Phase | Experiment | Discovered Tests | Reports | Status |",
    "| ---: | ---: | ---: | ---: | --- |"
)
foreach ($row in $rows) {
    $summaryLines += (
        "| {0} | {1} | {2} | {3} | {4} |" -f
        $row.Phase,
        $row.Experiment,
        $row.Tests,
        $row.Reports,
        $row.Status)
}
$summaryLines += ""
$summaryLines += if ($failed) {
    "Result: **FAIL** - at least one experiment is missing a test or report."
} else {
    "Result: **PASS** - every selected experiment has executable tests and one report."
}
Set-Content -Path $summaryPath -Value $summaryLines -Encoding UTF8

if ($failed) {
    Write-Host "Experiment inventory gate FAILED." -ForegroundColor Red
    exit 1
}

if ($Run) {
    $filter = switch ($Phase) {
        "2" { "FullyQualifiedName~Reliant.Tests.Integration.Phase2" }
        "3" { "FullyQualifiedName~Reliant.Tests.Integration.Phase3" }
        default {
            "FullyQualifiedName~Reliant.Tests.Integration.Phase2|" +
            "FullyQualifiedName~Reliant.Tests.Integration.Phase3"
        }
    }
    $resultsDirectory = Join-Path $ArtifactDir "test-results"
    New-Item -ItemType Directory -Force -Path $resultsDirectory |
        Out-Null
    dotnet test $testProject --no-build --configuration Debug --filter $filter --logger "trx;LogFileName=owner-experiments.trx" --results-directory $resultsDirectory
    if ($LASTEXITCODE -ne 0) { exit 1 }
}

Write-Host "Experiment inventory gate passed." -ForegroundColor Green
